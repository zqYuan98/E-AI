-- 公告附件里拆出来的具体项目（需求行），带所属分标、包、子包和原文位置；verdict 是按业务口径筛选的结果。
CREATE TABLE opp_items (
  id             bigserial PRIMARY KEY,
  notice_id      text NOT NULL REFERENCES opp_notices(id),
  ordinal        integer NOT NULL,
  section        text NOT NULL DEFAULT '',
  section_name   text NOT NULL DEFAULT '',
  package        text NOT NULL DEFAULT '',
  subpackage     text NOT NULL DEFAULT '',
  package_name   text NOT NULL DEFAULT '',
  project_name   text NOT NULL,
  buyer          text NOT NULL DEFAULT '',
  location       text NOT NULL DEFAULT '',
  scope          text NOT NULL DEFAULT '',
  qualifications text NOT NULL DEFAULT '',
  personnel      text NOT NULL DEFAULT '',
  performance    text NOT NULL DEFAULT '',
  ceiling        text NOT NULL DEFAULT '',
  ceiling_kind   text NOT NULL DEFAULT 'unknown',
  budget         text NOT NULL DEFAULT '',
  pricing        text NOT NULL DEFAULT '',
  evidence       jsonb NOT NULL DEFAULT '[]',
  verdict        text NOT NULL DEFAULT 'pending',
  line           text NOT NULL DEFAULT '',
  reason         text NOT NULL DEFAULT '',
  matched_by     text NOT NULL DEFAULT '',
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (notice_id, ordinal)
);
